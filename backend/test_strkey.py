# ---------------------------------------------------------------------------
# Base32 decode / CRC16 coupling tests
# ---------------------------------------------------------------------------

class StrKeyInternalsTest(unittest.TestCase):
    """Smoke-tests for the internal helpers to catch regressions."""

    def test_decode_base32_valid_g_address(self) -> None:
        decoded = _decode_base32(VALID_G_ADDRESS)
        self.assertEqual(len(decoded), 35)
        self.assertEqual(decoded[0], _VERSION_BYTE_ED25519_PUBLIC)

    def test_decode_base32_valid_c_contract(self) -> None:
        decoded = _decode_base32(VALID_C_CONTRACT)
        self.assertEqual(len(decoded), 35)
        self.assertEqual(decoded[0], _VERSION_BYTE_CONTRACT)

    def test_crc16_deterministic(self) -> None:
        data = b"hello"
        crc1 = _crc16_xmodem(data)
        crc2 = _crc16_xmodem(data)
        self.assertEqual(crc1, crc2)

    def test_crc16_different_for_different_data(self) -> None:
        crc1 = _crc16_xmodem(b"hello")
        crc2 = _crc16_xmodem(b"world")
        self.assertNotEqual(crc1, crc2)

    def test_make_strkey_roundtrip(self) -> None:
        """Encoding a version byte + payload must decode back to a valid StrKey."""
        import os
        payload = os.urandom(32)
        encoded = make_strkey(_VERSION_BYTE_ED25519_PUBLIC, payload)
        self.assertEqual(len(encoded), 56)
        self.assertTrue(is_valid_strkey(encoded, _VERSION_BYTE_ED25519_PUBLIC))


